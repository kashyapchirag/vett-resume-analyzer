import { z } from "zod";
import { ResumeMetadataSchema } from "./resume-schema";
import {
  MIN_JOB_DESCRIPTION_CHARS,
  MAX_JOB_DESCRIPTION_CHARS,
} from "../constants";

/**
 * Validation schema for the client request payload.
 * Enforces that the job description meets length and size bounds.
 */
export const AnalysisRequestSchema = z.object({
  jobDescription: z
    .string()
    .trim()
    .min(
      MIN_JOB_DESCRIPTION_CHARS,
      `Job description must be at least ${MIN_JOB_DESCRIPTION_CHARS} characters.`
    )
    .max(
      MAX_JOB_DESCRIPTION_CHARS,
      `Job description cannot exceed ${MAX_JOB_DESCRIPTION_CHARS.toLocaleString()} characters.`
    ),
});

/**
 * Individual categorical sub-scores generated by the LLM.
 * Each score is strictly constrained to an integer from 0 to 100.
 */
export const CategoryScoresSchema = z.object({
  skillsMatch: z
    .number()
    .int("Skills score must be an integer")
    .min(0, "Score cannot be less than 0")
    .max(100, "Score cannot exceed 100"),
  jobResponsibilities: z
    .number()
    .int("Responsibilities score must be an integer")
    .min(0, "Score cannot be less than 0")
    .max(100, "Score cannot exceed 100"),
  projectsAndExperience: z
    .number()
    .int("Projects score must be an integer")
    .min(0, "Score cannot be less than 0")
    .max(100, "Score cannot exceed 100"),
  keywordCoverage: z
    .number()
    .int("Keywords score must be an integer")
    .min(0, "Score cannot be less than 0")
    .max(100, "Score cannot exceed 100"),
});

/**
 * A skill directly found in the resume matching the job description,
 * backed by specific verbatim quote or evidence from the document.
 */
export const MatchedSkillSchema = z.object({
  skill: z.string().min(1, "Skill name cannot be empty"),
  evidence: z
    .string()
    .min(1, "Evidence citation from the resume cannot be empty"),
});

/**
 * Detailed alignment breakdown for duties and role expectations.
 */
export const ResponsibilityAlignmentSchema = z.object({
  strengths: z
    .array(z.string().min(1))
    .describe("Demonstrated duties matching the job requirements"),
  gaps: z
    .array(z.string().min(1))
    .describe("Required job duties where the resume lacks clear evidence"),
});

/**
 * Detailed assessment of project depth and work accomplishments.
 */
export const ProjectAssessmentSchema = z.object({
  strengths: z
    .array(z.string().min(1))
    .describe("Notable accomplishments, metrics, or domain projects"),
  gaps: z
    .array(z.string().min(1))
    .describe("Areas where project evidence is missing, generic, or unmeasured"),
});

/**
 * Structured output schema passed to the Vercel AI SDK (`Output.object`).
 * This enforces that the LLM decodes directly into typed data fields.
 */
export const LlmAnalysisOutputSchema = z.object({
  categoryScores: CategoryScoresSchema,
  matchedSkills: z.array(MatchedSkillSchema),
  missingSkills: z
    .array(z.string().min(1))
    .describe("Skills mentioned in the job description that were not demonstrated"),
  responsibilityAlignment: ResponsibilityAlignmentSchema,
  projectAssessment: ProjectAssessmentSchema,
  missingKeywords: z
    .array(z.string().min(1))
    .describe("Important industry terms or keywords from the job description missing from the resume"),
  actionableSuggestions: z
    .array(z.string().min(1))
    .describe("Prioritized recommendations to better communicate real qualifications"),
  formatObservations: z
    .array(z.string().min(1))
    .describe("Formatting observations regarding readability, sections, or structure"),
});

/**
 * Successful response contract for POST /api/analyze-resume.
 * Combines LLM analysis, deterministic application scoring, metadata, and disclaimer.
 */
export const AnalysisSuccessResponseSchema = z.object({
  success: z.literal(true),
  overallScore: z
    .number()
    .int()
    .min(0)
    .max(100)
    .describe("Deterministically calculated composite score using 35/25/25/15 weights"),
  scoreBand: z.enum([
    "Strong Alignment",
    "Moderate Alignment",
    "Needs Improvement",
  ]),
  analysis: LlmAnalysisOutputSchema,
  metadata: ResumeMetadataSchema,
  disclaimer: z.string(),
});

/**
 * Error response contract for POST /api/analyze-resume.
 */
export const AnalysisErrorResponseSchema = z.object({
  success: z.literal(false),
  error: z.string(),
  code: z.enum([
    "NO_FILE",
    "EMPTY_FILE",
    "FILE_TOO_LARGE",
    "UNSUPPORTED_FORMAT",
    "CORRUPTED_FILE",
    "ENCRYPTED_PDF",
    "SCANNED_PDF",
    "PARSE_FAILED",
    "INVALID_JOB_DESCRIPTION",
    "MISSING_API_KEY",
    "PROVIDER_ERROR",
    "RATE_LIMITED",
    "MALFORMED_OUTPUT",
  ]),
});

/**
 * Inferred TypeScript types derived directly from the runtime Zod schemas.
 */
export type AnalysisRequest = z.infer<typeof AnalysisRequestSchema>;
export type CategoryScores = z.infer<typeof CategoryScoresSchema>;
export type MatchedSkill = z.infer<typeof MatchedSkillSchema>;
export type ResponsibilityAlignment = z.infer<typeof ResponsibilityAlignmentSchema>;
export type ProjectAssessment = z.infer<typeof ProjectAssessmentSchema>;
export type LlmAnalysisOutput = z.infer<typeof LlmAnalysisOutputSchema>;
export type AnalysisSuccessResponse = z.infer<typeof AnalysisSuccessResponseSchema>;
export type AnalysisErrorResponse = z.infer<typeof AnalysisErrorResponseSchema>;
export type AnalysisResponse =
  | AnalysisSuccessResponse
  | AnalysisErrorResponse;
